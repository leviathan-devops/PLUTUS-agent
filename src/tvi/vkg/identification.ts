import type { AgentState, VKGNode } from '../types.js';

/** Working side from explicit state.side, else inferred from zone under evaluation. */
function sideOf(s: AgentState): 'supply' | 'demand' | undefined {
  if (s.side) return s.side;
  if (s.zone?.type === 'SUPPLY') return 'supply';
  if (s.zone?.type === 'DEMAND') return 'demand';
  return undefined;
}

/** Working zone type from explicit state.type, else from zone under evaluation. */
function typeOf(s: AgentState): string | undefined {
  return s.type ?? s.zone?.type;
}

/** Working classification from explicit state.classification, else from zone. */
function classOf(s: AgentState): string | undefined {
  return s.classification ?? s.zone?.classification;
}

